"""Canonical case schema (spec section 9)."""

from __future__ import annotations

from enum import StrEnum
from typing import Any

from pydantic import BaseModel, Field


class GoldProvenance(StrEnum):
    """Where a gold label came from (v2 spec 11.2 gold-confidence classes).

    Ordered strongest -> weakest. Primary release metrics preferentially
    emphasize the exact/proven provenances.
    """

    EXECUTION_EXACT = "execution_exact"
    BENCHMARK_EXACT = "benchmark_exact"
    RULE_EXACT = "rule_exact"
    EXPERT_CONSENSUS = "expert_consensus"
    ADJUDICATED = "adjudicated"
    SINGLE_EXPERT = "single_expert"
    HUMAN_LABELED = "human_labeled"
    RULE_DERIVED = "rule_derived"
    BENCHMARK_GOLD = "benchmark_gold"
    EXECUTION_DERIVED = "execution_derived"
    SYNTHETIC_DETERMINISTIC = "synthetic_deterministic"
    WEAK_INFERENCE = "weak_inference"


class GoldAnswer(BaseModel):
    """Gold answer for one question. Stored separately from the JEV input."""

    type: str
    # noul -> int/bool (0/1), choice -> str, score -> float
    value: float | int | bool | str
    provenance: GoldProvenance | None = None
    rubric_version: str | None = None
    # Optional annotation provenance for human-labeled cases (spec 16.2).
    annotators: list[str] = Field(default_factory=list)
    adjudicated: bool | None = None
    rationale_ref: str | None = None


class CaseSplit(StrEnum):
    """Benchmark-development splits (v2 spec 7.3).

    Only the last three provide strong evidence against overfitting.
    """

    TRAIN_VISIBLE = "train_visible"
    PUBLIC_VALIDATION = "public_validation"
    RELEASE_PUBLIC = "release_public"
    PRIVATE_HOLDOUT = "private_holdout"
    SECRET_RED_TEAM = "secret_red_team"
    FUTURE_TEMPORAL_HOLDOUT = "future_temporal_holdout"
    LEGACY = "legacy"


class CanonicalCase(BaseModel):
    """A versioned, typed evaluation test case."""

    schema_version: str = "2.0"
    case_id: str
    dataset: str
    dataset_version: str
    split: str = "test"
    # v2 benchmark-development split (spec 7.3); 'split' above retains the
    # v1 train/test meaning for legacy continuity.
    dev_split: CaseSplit | None = None
    capability: str
    # Secondary capabilities for cross-capability cases (spec 6.1): primary
    # counting uses `capability` only, preventing accidental over-weighting.
    secondary_capabilities: list[str] = Field(default_factory=list)
    tags: list[str] = Field(default_factory=list)
    state: str
    # Question packs may either be pre-baked into the case (questions+gold
    # aligned by question id) or generated by a registered pack.
    questions: dict[str, Any] = Field(default_factory=dict)
    gold: dict[str, GoldAnswer] = Field(default_factory=dict)
    metadata: dict[str, Any] = Field(default_factory=dict)

    # --- v2 fields (spec 6.2/6.3, 8, 32, 65) ---

    # Difficulty label from the written rubric (easy|medium|hard|expert).
    difficulty: str | None = None
    # Source class of this case's data.
    source: str | None = None
    # Upstream provenance: repo/revision/source-id for adapter-derived cases.
    source_ref: str | None = None
    # Generator provenance for synthetic/variant cases (spec 32).
    generator: str | None = None
    generator_version: str | None = None
    generator_seed: int | None = None
    parent_case_id: str | None = None
    # Metamorphic relation to the parent (invariant|flip_expected|
    # bounded_change|independent) — spec 15.
    relation: str | None = None
    # True for generated variants: never counted as primary samples
    # (invariant 1, spec 64).
    is_variant: bool = False
    # Cluster key for correlated cases (repository, episode, family) —
    # cluster-aware bootstrap uses this (spec 35.3).
    cluster_key: str | None = None
    # Contamination flag (spec 73): permanently set when a case is known
    # to the training pipeline.
    contaminated: bool = False

    def question_type(self, question_id: str) -> str | None:
        q = self.questions.get(question_id)
        if isinstance(q, dict):
            return q.get("type")
        return None

    @property
    def is_primary_sample(self) -> bool:
        """Primary sample = not a generated variant (spec 64, invariant 1-2)."""
        return not self.is_variant
